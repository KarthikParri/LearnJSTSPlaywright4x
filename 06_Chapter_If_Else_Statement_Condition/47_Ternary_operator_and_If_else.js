// Ternary operator is a conditional operator that takes three operands. It is used to evaluate a condition and return one of two values based on whether the condition is true or false. The syntax for the ternary operator is as follows:
// condition ? value_if_true : value_if_false
let age = 20;
let result = age > 21 ? "Drive": "No Able to Drive";
console.log(result);

// The above code is equivalent to the following if-else statement:
if(age > 21){
    console.log("Drive");
    console.log("Drink");
    console.log("Go goa");
}else{
    console.log("No Able to Drive");
}